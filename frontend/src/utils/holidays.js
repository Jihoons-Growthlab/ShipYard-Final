export function dayKind(date) {
  if (HOLIDAYS[date]) return 'hol'
  const w = dow(date)
  return w === 0 ? 'sun' : w === 6 ? 'sat' : null
}

/** 간트 범위의 휴일·주말: [{date, x, kind:'sat'|'sun'|'hol', name}] */
export function offDays(layout, scale = layout.scale) {
  const out = []
  for (let i = 0; i < layout.days; i++) {
    const date = addDays(layout.start, i)
    const kind = dayKind(date)
    if (kind) out.push({ date, x: i * scale, kind, name: HOLIDAYS[date] || '' })
  }
  return out
}
